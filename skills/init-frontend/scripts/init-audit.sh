#!/usr/bin/env bash
# init-audit.sh — Run quality gates: token audit, a11y, performance budget, responsive check.
#
# Usage:
#   init-audit.sh [project-dir]
#
set -euo pipefail

log() { echo "[init-frontend audit] $*"; }

PROJECT_DIR="${1:-$(pwd)}"
EVIDENCE_DIR="$PROJECT_DIR/.ufme/evidence"
mkdir -p "$EVIDENCE_DIR"

RESULTS=()

check() {
  local name="$1"; local cmd="$2"
  if eval "$cmd"; then
    RESULTS+=("PASS: $name")
    log "PASS: $name"
  else
    RESULTS+=("FAIL: $name")
    log "FAIL: $name"
  fi
}

echo "=== UFMW Init-Frontend Audit ==="

# Token audit
check "design tokens exist" "[ -d '$PROJECT_DIR/src/tokens' ]"
check "color tokens" "[ -f '$PROJECT_DIR/src/tokens/color.json' ]"
check "typography tokens" "[ -f '$PROJECT_DIR/src/tokens/typography.json' ]"
check "spacing tokens" "[ -f '$PROJECT_DIR/src/tokens/spacing.json' ]"

# Accessibility checks
check "base CSS has focus-visible" "grep -q 'focus-visible' '$PROJECT_DIR/src/styles/base.css'"
check "base CSS has min-height 24px" "grep -q 'min-height: 24px' '$PROJECT_DIR/src/styles/base.css'"
check "reduced motion support" "grep -q 'prefers-reduced-motion' '$PROJECT_DIR/src/styles/base.css'"

# Performance budget
check "perf budget config" "[ -f '$PROJECT_DIR/perf-budget.json' ]"

# Write results
{
  printf '{\n  "checks": %d,\n  "pass": %d,\n  "failed": %d,\n  "results": [\n' \
    "$((${#RESULTS[@]}))" "$(printf '%s\n' "${RESULTS[@]}" | grep -c '^PASS')" "$(printf '%s\n' "${RESULTS[@]}" | grep -c '^FAIL')"
  first=1
  for result in "${RESULTS[@]}"; do
    [ "$first" -eq 1 ] || printf ',\n'
    first=0
    status="${result%%:*}"
    printf '    {"status": "%s", "name": "%s"}' "$status" \
      "$(printf '%s' "${result#*: }" | sed 's/\\/\\\\/g; s/"/\\"/g')"
  done
  printf '\n  ]\n}\n'
} > "$EVIDENCE_DIR/audit-results.json"

# Audit report
{
  echo "# Audit Report"
  echo ""
  echo "Generated by: ufmw init-frontend audit"
  echo ""
  echo "## Results"
  echo ""
  for result in "${RESULTS[@]}"; do
    status="${result%%:*}"
    name="${result#*: }"
    if [ "$status" = "PASS" ]; then
      echo "- [x] $name"
    else
      echo "- [ ] $name"
    fi
  done
  echo ""
  echo "## Standards"
  echo "- WCAG 2.2 AA"
  echo "- Performance: LCP ≤ 2.5s, INP ≤ 200ms, CLS ≤ 0.1"
  echo "- Input budget: JS ≤ 300KB, CSS ≤ 100KB, images ≤ 200KB"
} > "$PROJECT_DIR/.ufme/AUDIT_REPORT.md"

FAIL_COUNT=$(printf '%s\n' "${RESULTS[@]}" | grep -c '^FAIL' || true)
echo ""
if [ "$FAIL_COUNT" -eq 0 ]; then
  log "All audit checks passed."
  exit 0
else
  log "$FAIL_COUNT audit check(s) failed. See $PROJECT_DIR/.ufme/AUDIT_REPORT.md"
  exit 1
fi
