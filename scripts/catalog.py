#!/usr/bin/env python3
"""catalog.py — generate CATALOG.md and mirror the catalog into `.opencode/`.

Source of truth:
  skills/<name>/SKILL.md   -> `.opencode/skills/<name>/SKILL.md`
  commands/**/*.md         -> `.opencode/commands/**/*.md`
  agents/*.md              -> mirrored by scripts/build-agents.py, listed here

`CATALOG.md` is generated from those files. `--check` exits non-zero when the
catalog or the mirror is out of date.

Pure python3; writes only CATALOG.md and `.opencode/`.
"""

import argparse
import re
import shutil
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
CATALOG = PROJECT_ROOT / "CATALOG.md"
MIRROR = PROJECT_ROOT / ".opencode"
HEADER = "<!-- generated by scripts/catalog.py — do not edit by hand -->"


def frontmatter(path):
    """Return frontmatter fields as a flat dict (nested blocks are ignored)."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end < 0:
        return {}
    fields = {}
    for line in text[4:end].splitlines():
        if not line.strip() or line[0] in " \t":
            continue
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    return fields


def describe(path, fallback=""):
    return frontmatter(path).get("description") or fallback


def cell(text):
    return text.replace("|", "\\|").strip()


def discover():
    skills = []
    for path in sorted((PROJECT_ROOT / "skills").glob("*/SKILL.md")):
        fields = frontmatter(path)
        skills.append(
            {
                "name": fields.get("name", path.parent.name),
                "description": describe(path, "(no description)"),
                "path": path.relative_to(PROJECT_ROOT).as_posix(),
            }
        )
    agents = []
    for path in sorted((PROJECT_ROOT / "agents").glob("*.md")):
        fields = frontmatter(path)
        agents.append(
            {
                "name": fields.get("name", path.stem),
                "mode": fields.get("mode", "?"),
                "description": describe(path, "(no description)"),
                "path": path.relative_to(PROJECT_ROOT).as_posix(),
            }
        )
    commands = []
    for path in sorted((PROJECT_ROOT / "commands").rglob("*.md")):
        commands.append(
            {
                "name": path.relative_to(PROJECT_ROOT / "commands").with_suffix("").as_posix(),
                "description": describe(path, "(no description)"),
                "path": path.relative_to(PROJECT_ROOT).as_posix(),
            }
        )
    return skills, agents, commands


def render(skills, agents, commands):
    lines = [
        HEADER,
        "",
        "# Catalog",
        "",
        "Every skill, agent, and command in this repo, in one place.",
        "Generated from the tree; run `python3 scripts/catalog.py` after moving files.",
        "",
        f"**{len(skills)} skills · {len(agents)} agents · {len(commands)} commands**",
        "",
        "## Skills",
        "",
        "| Skill | What it does | Path |",
        "|-------|--------------|------|",
    ]
    for s in skills:
        lines.append(f"| `{s['name']}` | {cell(s['description'])} | `{s['path']}` |")
    lines += [
        "",
        "## Agents",
        "",
        "| Agent | Mode | What it does | File |",
        "|-------|------|--------------|------|",
    ]
    for a in agents:
        lines.append(
            f"| `{a['name']}` | {a['mode']} | {cell(a['description'])} | `{a['path']}` |"
        )
    lines += [
        "",
        "## Commands",
        "",
        "| Command | What it does | File |",
        "|---------|--------------|------|",
    ]
    for c in commands:
        lines.append(f"| `/{c['name']}` | {cell(c['description'])} | `{c['path']}` |")
    lines.append("")
    return "\n".join(lines)


def mirror_files():
    """Map mirror destination -> source for files catalog.py owns."""
    pairs = {}
    for path in sorted((PROJECT_ROOT / "commands").rglob("*.md")):
        rel = path.relative_to(PROJECT_ROOT / "commands")
        pairs[MIRROR / "commands" / rel] = path
    for path in sorted((PROJECT_ROOT / "skills").glob("*/SKILL.md")):
        pairs[MIRROR / "skills" / path.parent.name / "SKILL.md"] = path
    return pairs


def sync_mirror():
    for target, source in mirror_files().items():
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.is_file() or target.read_bytes() != source.read_bytes():
            shutil.copyfile(source, target)
            print(f"mirrored: {target.relative_to(PROJECT_ROOT)}")
    for root in (MIRROR / "commands", MIRROR / "skills"):
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*")):
            if path.is_file() and path not in mirror_files():
                path.unlink()
                print(f"removed obsolete: {path.relative_to(PROJECT_ROOT)}")


def check_mirror():
    drift = []
    pairs = mirror_files()
    for target, source in pairs.items():
        if not target.is_file():
            drift.append(f"{target.relative_to(PROJECT_ROOT)} missing")
        elif target.read_bytes() != source.read_bytes():
            drift.append(f"{target.relative_to(PROJECT_ROOT)} drifts from {source.relative_to(PROJECT_ROOT)}")
    for root in (MIRROR / "commands", MIRROR / "skills"):
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*")):
            if path.is_file() and path not in pairs:
                drift.append(f"obsolete mirror file: {path.relative_to(PROJECT_ROOT)}")
    return drift


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit non-zero on drift")
    args = parser.parse_args()

    skills, agents, commands = discover()
    if not skills or not agents:
        print("no skills or agents found", file=sys.stderr)
        return 2
    rendered = render(skills, agents, commands)

    if args.check:
        drift = []
        if not CATALOG.is_file() or CATALOG.read_text(encoding="utf-8") != rendered:
            drift.append("CATALOG.md is out of date")
        drift += check_mirror()
        for item in drift:
            print(f"DRIFT: {item}")
        if drift:
            return 1
        print("check: catalog and mirror in sync")
        return 0

    CATALOG.write_text(rendered, encoding="utf-8")
    print(f"wrote {CATALOG.relative_to(PROJECT_ROOT)}")
    sync_mirror()
    return 0


if __name__ == "__main__":
    sys.exit(main())
